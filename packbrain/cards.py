"""Karteikarten (fact cards): short, verified summaries per item, mob, structure or mod mechanic.

Written offline by a larger model (extract/make_cards.py, e.g. Qwen at night) from the same evidence the live agent sees;
every number in a card was checked against that evidence before it was stored. The live system only reads them:
  * hotkey H shows an item's card instantly (no model call),
  * agent v3 adds a subject's card as an evidence record.

Cards live in their own file (db/cards.sqlite), so rebuilding the knowledge base does not delete them. A card whose
evidence changed after a rebuild (different evidence hash) is regenerated by the next card run.
"""
import sqlite3
import threading
import time
from pathlib import Path

CARDS_PATH = Path(__file__).resolve().parent.parent / "db" / "cards.sqlite"
_lock = threading.Lock()
_conn = {}

SCHEMA = """CREATE TABLE IF NOT EXISTS cards(
  key TEXT PRIMARY KEY, kind TEXT, ref TEXT, mod TEXT, lang TEXT, title TEXT, text TEXT,
  evidence_hash TEXT, model TEXT, created TEXT, status TEXT, issues TEXT)"""


def conn(path=None, write=False):
    path = Path(path or CARDS_PATH)
    k = (str(path), write)
    with _lock:
        if k not in _conn:
            if not write and not path.exists():
                return None
            path.parent.mkdir(parents=True, exist_ok=True)
            c = sqlite3.connect(str(path), check_same_thread=False, timeout=10)
            c.row_factory = sqlite3.Row
            if write:
                c.execute(SCHEMA)
                c.commit()
            _conn[k] = c
        return _conn[k]


def key(kind, ref, lang):
    return f"{kind}:{ref}:{lang}"


def get(kind, ref, lang="de", path=None):
    """Text of a verified card, or None."""
    c = conn(path)
    if c is None:
        return None
    try:
        r = c.execute("SELECT text FROM cards WHERE key=? AND status='ok'", (key(kind, ref, lang),)).fetchone()
    except sqlite3.OperationalError:
        return None
    return r["text"] if r else None


def get_row(kind, ref, lang="de", path=None):
    c = conn(path)
    if c is None:
        return None
    try:
        return c.execute("SELECT * FROM cards WHERE key=?", (key(kind, ref, lang),)).fetchone()
    except sqlite3.OperationalError:
        return None


def put(kind, ref, mod, lang, title, text, evidence_hash, model, status="ok", issues="", path=None):
    c = conn(path, write=True)
    c.execute("INSERT OR REPLACE INTO cards VALUES (?,?,?,?,?,?,?,?,?,?,?,?)",
              (key(kind, ref, lang), kind, ref, mod, lang, title, text, evidence_hash, model,
               time.strftime("%Y-%m-%dT%H:%M:%S"), status, issues))
    c.commit()


def stats(path=None):
    c = conn(path)
    if c is None:
        return {}
    try:
        return {f"{r['kind']}/{r['status']}": r["n"] for r in c.execute("SELECT kind, status, count(*) n FROM cards GROUP BY kind, status")}
    except sqlite3.OperationalError:
        return {}
